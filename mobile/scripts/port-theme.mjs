// Ports the web client's built-in themes (client/src/index.css) to the app.
//
// React Native has no oklch(), so every value is converted to sRGB here, once,
// at build time. The output is Uniwind theme blocks (src/theme/themes.css) and
// the same values as data (src/theme/themes.generated.ts) for the places that
// need a colour outside a className — the status bar, the navigation bar.
//
// Re-run after the web palette changes:
//   npm run port-theme
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, "../../client/src/index.css");
const css = fs.readFileSync(src, "utf8");

function oklchToRgb(L, C, H) {
  const h = (H * Math.PI) / 180;
  const a = C * Math.cos(h);
  const b = C * Math.sin(h);
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = L - 0.0894841775 * a - 1.291485548 * b;
  const l = l_ ** 3;
  const m = m_ ** 3;
  const s = s_ ** 3;
  const lin = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
  return lin.map((x) => {
    const v = x <= 0.0031308 ? 12.92 * x : 1.055 * Math.pow(x, 1 / 2.4) - 0.055;
    return Math.round(Math.min(1, Math.max(0, v)) * 255);
  });
}

const hex = (rgb) => "#" + rgb.map((x) => x.toString(16).padStart(2, "0")).join("");

function convert(value) {
  const m = value.match(/^oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*(?:\/\s*([\d.]+)(%?))?\s*\)$/);
  if (!m) return value;
  const rgb = oklchToRgb(+m[1], +m[2], +m[3]);
  if (m[4] === undefined) return hex(rgb);
  const alpha = m[5] ? +m[4] / 100 : +m[4];
  return `rgba(${rgb.join(", ")}, ${alpha})`;
}

// Each theme block: `[data-theme="id"] { --name: value; ... }`. The base light
// and dark blocks are aliased to `[data-theme="light"|"dark"]` in index.css.
const themes = {};
const blockRe = /((?:[:.\w-]+|\[data-theme="[\w-]+"\])(?:,\s*(?:[:.\w-]+|\[data-theme="[\w-]+"\]))*)\s*\{([^}]*)\}/g;
for (const [, selectors, body] of css.matchAll(blockRe)) {
  const ids = [...selectors.matchAll(/data-theme="([\w-]+)"/g)].map((m) => m[1]);
  if (!ids.length) continue;
  const vars = {};
  for (const [, name, value] of body.matchAll(/--([\w-]+):\s*([^;]+);/g)) vars[name] = convert(value.trim());
  for (const id of ids) themes[id] = { ...(themes[id] ?? {}), ...vars };
}
if (!themes.light || !themes.dark) throw new Error(`No light/dark base found in ${src}`);

// Named themes override only what they change; the rest falls through to the
// dark base, as `.dark` does on the web.
for (const [id, vars] of Object.entries(themes)) {
  if (id !== "light" && id !== "dark") themes[id] = { ...themes.dark, ...vars };
}

// Colours only: radius and the like are layout, declared once in global.css.
// Uniwind requires every theme to declare the same set.
const colourNames = Object.keys(themes.dark).filter((k) => /^(#|rgb)/.test(themes.dark[k]));
for (const [id, vars] of Object.entries(themes)) {
  for (const k of colourNames) if (!(k in vars)) throw new Error(`Theme ${id} is missing --${k}`);
}

// The web's own list, for names and modes. Kept in sync by hand there.
const themesTs = fs.readFileSync(path.resolve(here, "../../client/src/lib/theme/themes.ts"), "utf8");
const meta = [...themesTs.matchAll(/\{ id: "([\w-]+)", name: "([^"]+)", mode: "(light|dark)"/g)].map(
  ([, id, name, mode]) => ({ id, name, mode }),
);
for (const { id } of meta) if (!themes[id]) throw new Error(`index.css has no block for theme ${id}`);

// A slot for a theme built in the app (or synced from the web) at runtime:
// Uniwind needs it declared at build time, and `Uniwind.updateCSSVariables`
// fills it in. Its build-time values are Default Dark's.
const CUSTOM = "custom";
const all = { ...Object.fromEntries(meta.map(({ id }) => [id, themes[id]])), [CUSTOM]: themes.dark };

const block = (vars) => colourNames.map((k) => `      --color-${k}: ${vars[k]};`).join("\n");
const out = `/* GENERATED by scripts/port-theme.mjs from client/src/index.css. Do not edit. */
@layer theme {
  :root {
${Object.entries(all)
  .map(([id, vars]) => `    @variant ${id} {\n${block(vars)}\n    }`)
  .join("\n")}
  }
}
`;
fs.writeFileSync(path.resolve(here, "../src/theme/themes.css"), out);

const data = Object.fromEntries(
  Object.entries(all).map(([id, vars]) => [id, Object.fromEntries(colourNames.map((k) => [k, vars[k]]))]),
);
const ts = `// GENERATED by scripts/port-theme.mjs from client/src/index.css. Do not edit.

/** The colour tokens every theme defines, as the web names them. */
export type ThemeToken =
${colourNames.map((k) => `  | "${k}"`).join("\n")};

export type ThemeColors = Record<ThemeToken, string>;

export interface BuiltInTheme {
  id: string;
  name: string;
  mode: "light" | "dark";
}

/** The web's built-in themes, in its order (client/src/lib/theme/themes.ts). */
export const BUILT_IN_THEMES: BuiltInTheme[] = ${JSON.stringify(meta, null, 2)};

/** The slot a runtime theme is written into. */
export const CUSTOM_THEME_ID = "${CUSTOM}";

/** Every theme the stylesheet knows, by id. */
export const THEME_COLORS: Record<string, ThemeColors> = ${JSON.stringify(data, null, 2)};

/** Every theme name Uniwind must be told about (metro.config.js \`extraThemes\`). */
export const THEME_IDS = ${JSON.stringify(Object.keys(all))};
`;
fs.writeFileSync(path.resolve(here, "../src/theme/themes.generated.ts"), ts);
fs.writeFileSync(path.resolve(here, "../src/theme/theme-ids.json"), JSON.stringify(Object.keys(all)) + "\n");

console.log(`themes: ${Object.keys(all).join(", ")} · ${colourNames.length} colour tokens`);
